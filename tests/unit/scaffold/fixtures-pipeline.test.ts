// CC-01.2: `pnpm fixtures` regenerates `fixtures/` matching committed checksums.
//
// Contract: US-1.0.2 — "Given `pnpm fixtures`, when run, then `fixtures/` contains
// the eval corpus …"; "Given a corrupted fixture file, when `pnpm test`, then
// fixture verification fails loudly with the checksum diff"; "Given any fixture
// missing its license record, when CI `fixtures-verify` runs, then it fails".
//
// The generator is never mocked: it runs in a scratch copy of the repository so
// the checkout's own fixtures stay untouched (Film-QA style: expected vs actual
// state, side effects only inside the scratch tree).
import { afterAll, describe, expect, test } from 'vitest'
import { createHash } from 'node:crypto'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { copyTree, exists, isPlaceholderScript, packageScripts, removeScratch, runIn, scratchDir, writeFixtureFile } from '../../helpers/repo'

interface Manifest {
  files: Record<string, { sha256: string; generated: boolean }>
}

function digest(file: string): string {
  return createHash('sha256').update(readFileSync(file)).digest('hex')
}

function manifestPath(tree: string): string {
  for (const candidate of ['fixtures/harness/manifest.json', 'fixtures/manifest.json', 'harness/manifest.json']) {
    if (existsSync(join(tree, candidate))) return join(tree, candidate)
  }
  return join(tree, 'fixtures/harness/manifest.json')
}

function committedFixtures(tree: string): string[] {
  const manifestFile = manifestPath(tree)
  if (!existsSync(manifestFile)) return []
  const manifest = JSON.parse(readFileSync(manifestFile, 'utf8')) as Manifest
  return Object.entries(manifest.files)
    .filter(([, entry]) => !entry.generated)
    .map(([name]) => join(tree, 'fixtures', 'audio', name))
    .filter((file) => existsSync(file))
}

const trees: string[] = []
afterAll(() => trees.splice(0).forEach(removeScratch))

function scratchTree(label: string): string {
  const dir = scratchDir(`fixtures-${label}`)
  copyTree('.', dir, { skip: ['fixtures/audio', 'fixtures/sources'] })
  trees.push(dir)
  return dir
}

describe('CC-01.2: fixture regeneration and verification', () => {
  test('CC-01.2: `pnpm fixtures` is a real generator (not a placeholder script)', () => {
    const script = packageScripts().fixtures
    expect(isPlaceholderScript(script), `fixtures = ${script ?? '<missing>'}`).toBe(false)
    expect(exists('scripts/make-fixtures.ts') || exists('scripts/make-fixtures.mjs'), 'scripts/make-fixtures.ts').toBe(true)
  })

  test('CC-01.2: `pnpm fixtures` regenerates committed fixtures with matching SHA-256 checksums', () => {
    const tree = scratchTree('regen')
    const run = runIn(tree, 'corepack', ['pnpm', 'run', '--silent', 'fixtures'], 30_000)
    expect(run.status, `pnpm fixtures failed\n${run.output.slice(-6000)}`).toBe(0)
    const manifest = JSON.parse(readFileSync(manifestPath(tree), 'utf8')) as Manifest
    const drift = Object.entries(manifest.files)
      .filter(([name, entry]) => !entry.generated && existsSync(join(tree, 'fixtures/audio', name)))
      .filter(([name, entry]) => digest(join(tree, 'fixtures/audio', name)) !== entry.sha256)
      .map(([name]) => name)
    expect(drift, 'regenerated fixtures must hash to their committed checksums').toEqual([])
    expect(committedFixtures(tree).length, 'at least one committed fixture is generated by the script').toBeGreaterThan(0)
  })

  test('CC-01.2: a corrupted fixture makes fixture verification fail with the checksum diff', () => {
    const tree = scratchTree('corrupt')
    expect(existsSync(manifestPath(tree)), 'fixtures manifest committed (run `pnpm fixtures` first)').toBe(true)
    const target = committedFixtures(tree)[0]
    expect(target, 'a committed fixture to corrupt').toBeDefined()
    const original = readFileSync(target!)
    writeFileSync(target!, Buffer.concat([original, Buffer.from([0, 1, 2, 3])]))
    const manifest = JSON.parse(readFileSync(manifestPath(tree), 'utf8')) as Manifest
    const name = Object.keys(manifest.files).find((key) => join(tree, 'fixtures/audio', key) === target)!
    const expected = manifest.files[name]!.sha256
    const actual = digest(target!)
    const verify = runIn(tree, 'corepack', ['pnpm', 'run', '--silent', 'fixtures:verify'], 30_000)
    if (verify.status === null && /missing script/i.test(verify.output)) {
      throw new Error('package.json has no `fixtures:verify` script; CI `fixtures-verify` needs one (FR-1.0.7)')
    }
    expect(verify.status, `corrupt fixture must fail verification\n${verify.output.slice(-4000)}`).not.toBe(0)
    expect(actual).not.toBe(expected)
    const diffs = [expected, actual].filter((hash) => verify.output.includes(hash))
    expect(diffs.length, `the failure must print the checksum diff (expected ${expected}, actual ${actual})\n${verify.output.slice(-4000)}`).toBe(2)
  })

  test('CC-01.2: an unlicensed fixture fails `fixtures:verify` (LICENSES.md completeness)', () => {
    const tree = scratchTree('license')
    writeFixtureFile(join(tree, 'fixtures/LICENSES.md'), '# Fixtures — licenses\n\n| Source | License | URL |\n|---|---|---|\n')
    const verify = runIn(tree, 'corepack', ['pnpm', 'run', '--silent', 'fixtures:verify'], 30_000)
    expect(verify.status, `a fixture without a license record must fail\n${verify.output.slice(-4000)}`).not.toBe(0)
    expect(verify.output).toMatch(/licen[sc]e/i)
  })
})