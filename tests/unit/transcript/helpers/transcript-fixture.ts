/** Virtualization probe: `count` uniform 1-second blocks (ids blk_p<idx>,
 *  speakers alternating) — synthetic words only, no canary (rows are many;
 *  the canary stays in the small suites). */
export function bulkBlocks(count: number): CaptionBlock[] {
  const blocks: CaptionBlock[] = []
  for (let index = 0; index < count; index++) {
    const start = Math.round(index * 1.0 * 1000) / 1000
    const end = Math.round((index * 1.0 + 0.9) * 1000) / 1000
    blocks.push(block(`blk_p${index}`, start, end, index % 2 === 0 ? 'SPK_1' : 'SPK_2', [word(`synthetic${index}`, start, end)]))
  }
  return blocks
}

