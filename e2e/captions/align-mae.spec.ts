// CC-07.3 (L4): honest word-timing MAE — the REAL pipeline (media worker
// decode → real asr.worker via createAsrWorkerHost → real importCaptions of
// the vendored human CART captions → real alignCaptionsToWords with the run's
// ASR words) must bring aligned word times within 1.5× the spike
// direct-transcription baseline measured on the SAME clip and GT
// (docs/spikes/model-eval-report.json wordTimingMAEms — READ, never invented).
//
// MAE definition (pinned here): mean over caption words that are BOTH
// ASR-aligned and GT-correspondent of (|aligned.start − gt.start| +
// |aligned.end − gt.end|) / 2. Words the aligner left 'estimated' are
// excluded (they are re-interpolated, not ASR evidence — counting them would
// let a no-op aligner "score"). Caption↔GT correspondence is the monotone
// (LCS) matching over normalized tokens — the CART captions are verbatim
// as-delivered (chunk-drop holes, speaker-tag lines) while the GT is repaired
// from Hansard (see provenance below), so index pairing is undefined.
//
// Corpus (owner ruling 2026-11-09, supersedes the interim sine-formant
// corpus for this criterion): Senate of Canada Sitting No. 101 (2026-11-05),
// SenParlVu meeting 15671 — real speech with human CART captions verified
// verbatim against the official Debates of the Senate; word-level GT = CART
// wording with the 7 feed chunk-drop cues repaired from Hansard (Open
// Parliament Licence 1.0, attribution in fixtures/LICENSES.md; regenerated by
// scripts/fetch-vendor-fixtures.ts). Caveats: GT word boundaries are
// caption-granular (~0.9 s cues, even-split inside cues) — the same coarse
// timeline backs the harness baseline row (A-tiny-wasm-senate-veterans,
// measured by tools/eval/harness.mjs), so the ×1.5 comparison is like-for-
// like; whisper-tiny's absolute timing numbers on long-form speech stay the
// spike's quality story — this assertion is a regression guard, not a quality
// claim. The sine-formant speech-2min corpus remains the determinism fixture
// of the unit-05 specs (no quality assertion on it). The alignedRatio > 0
// non-vacuity check is what keeps the MAE assertion from being satisfied by
// zero aligned words.
//
// Align INPUT (ledger 2026-11-09): two separate timeline issues were found
// and fixed. (1) The clip's media window had been cut 33 s late (the
// player's PreRoll constant was wrong for this VOD), putting every word
// 33 s ahead of the caption timeline; the fetch script now cuts with the
// empirically pinned offset (whisper Δ median −0.19 s, n=252) and
// whisper-tiny's native word timing is genuinely good (spike baseline
// wordTimingMAEms ≈ 1.6 s). (2) What remains is feed granularity: the CART
// delivers ~0.65 s micro-cues that split mid-sentence ('pause and look upon
// the' as its own cue), and the aligner's frozen boundary guards (align.ts)
// only accept ASR evidence whose timing falls inside the caption block's
// span — which residual ±1–3 s word-timing scatter cannot fit. Alignment
// therefore runs on the blocked variant — same committed token stream and
// order, cues merged into ≈60-word paragraph blocks by
// scripts/fetch-vendor-fixtures.ts (--blocked), i.e. the block granularity
// real-world caption BLOCKS have. The as-delivered micro-cue files remain
// the parser fixtures.
import { expect, test } from '@playwright/test'
import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { REPO_ROOT } from '../../tests/helpers/repo'
import { assertModelCachePresent, routeAsrNetwork, startHarnessServer, stopHarnessServer, type HarnessServer, type NetworkCounters } from '../asr/helpers/asr'
import type { AlignRunOptions, AlignRunSummary } from './fixtures/align-harness'

const PORT = 4315
const MAE_MULTIPLIER = 1.5
const CORPUS_CLIP = 'senate-veterans-2min'

let server: HarnessServer | undefined

interface GroundTruthWord {
  text: string
  start: number
  end: number
}

/** The direct-transcription word-timing baseline on the same clip + GT —
 *  read from the spike artifact row measured by tools/eval/harness.mjs
 *  (whisper-tiny T2, corpusClip-pinned), never invented (unit-02 doctrine). */
function spikeTinyWordTimingMaeBaseline(): { value: number; source: string } {
  const report = JSON.parse(readFileSync(join(REPO_ROOT, 'docs/spikes/model-eval-report.json'), 'utf8')) as {
    rows: { engine: string; model: string; tier: string; ok?: boolean; corpusClip?: string; wordTimingMAEms?: number }[]
  }
  const row = report.rows.find((r) => r.model === 'onnx-community/whisper-tiny_timestamped' && r.tier === 'T2' && r.engine === 'transformers.js' && r.corpusClip === CORPUS_CLIP && r.ok === true)
  if (!row || row.wordTimingMAEms === undefined) throw new Error(`docs/spikes/model-eval-report.json has no ok:true whisper-tiny T2 wordTimingMAEms row for corpusClip=${CORPUS_CLIP} (re-run: node tools/eval/harness.mjs --mode=rows --plan=A-tiny-wasm-senate-veterans)`)
  return { value: row.wordTimingMAEms, source: `docs/spikes/model-eval-report.json rows[whisper-tiny_timestamped,T2,${CORPUS_CLIP}].wordTimingMAEms` }
}

const normalizeToken = (text: string): string => text.toLowerCase().replace(/[^\p{L}\p{N}\s]/gu, '').trim()

/** Raw whitespace tokens of the committed VTT cue texts — mirrors the
 *  engine's caption word stream (identifier-less cues, one text line each;
 *  CART text is plain, so tag-stripping is a no-op) for the node-side
 *  text-invariance and pairing inputs. */
function vttCueTokens(file: string): string[] {
  const tokens: string[] = []
  for (const line of readFileSync(join(REPO_ROOT, file), 'utf8').replace(/\r\n?/g, '\n').split('\n')) {
    const trimmed = line.trim()
    if (trimmed === '' || /^WEBVTT(\b|[ \t])/.test(trimmed) || trimmed.includes('-->')) continue
    tokens.push(...trimmed.split(/\s+/))
  }
  return tokens
}

function countVttCues(file: string): number {
  return readFileSync(join(REPO_ROOT, file), 'utf8').split('\n').filter((line) => line.includes('-->')).length
}

/** Monotone (LCS) caption→GT token correspondence: gtIndex per caption
 *  index, -1 unmatched. Empty-normalized tokens never match. Deterministic
 *  backtrack (prefer take on ties). */
function monotoneGtIndices(captionNorm: string[], gtNorm: string[]): number[] {
  const n = captionNorm.length
  const m = gtNorm.length
  const dp: number[] = new Array((n + 1) * (m + 1)).fill(0)
  for (let i = n - 1; i >= 0; i--) {
    for (let j = m - 1; j >= 0; j--) {
      const a = captionNorm[i]!
      const b = gtNorm[j]!
      const take = a !== '' && a === b ? dp[(i + 1) * (m + 1) + j + 1]! + 1 : 0
      dp[i * (m + 1) + j] = Math.max(dp[(i + 1) * (m + 1) + j]!, dp[i * (m + 1) + j + 1]!, take)
    }
  }
  const indices: number[] = new Array(n).fill(-1)
  let i = 0
  let j = 0
  while (i < n && j < m) {
    const a = captionNorm[i]!
    const b = gtNorm[j]!
    const take = a !== '' && a === b ? dp[(i + 1) * (m + 1) + j + 1]! + 1 : 0
    if (take > 0 && take >= dp[(i + 1) * (m + 1) + j]! && take >= dp[i * (m + 1) + j + 1]!) {
      indices[i] = j
      i += 1
      j += 1
      continue
    }
    if (dp[(i + 1) * (m + 1) + j]! >= dp[i * (m + 1) + j + 1]!) i += 1
    else j += 1
  }
  return indices
}

test.describe('CC-07.3: caption↔ASR alignment honest word-timing MAE vs spike baseline', () => {
  test.skip(process.env.ZIPSCRIBE_CHILD === '1', 'gates-scaffold child run: authoritative execution is the parent `pnpm test:e2e`')
  test.use({ baseURL: `http://127.0.0.1:${PORT}` })
  test.setTimeout(15 * 60_000)

  test.beforeAll(async () => {
    assertModelCachePresent()
    server = await startHarnessServer(PORT, { isolated: false, probePath: '/e2e/captions/fixtures/align-harness.html' })
  })
  test.afterAll(async () => {
    if (server) await stopHarnessServer(server.child)
  })

  test('CC-07.3: aligned caption words over senate-veterans-2min.mp4 stay within 1.5× the spike word-timing MAE baseline', async ({ page }) => {
    const { value: baseline, source } = spikeTinyWordTimingMaeBaseline()
    const groundTruth = (JSON.parse(readFileSync(join(REPO_ROOT, `fixtures/harness/ground-truth/${CORPUS_CLIP}.json`), 'utf8')) as { words: GroundTruthWord[] }).words
    const captionTokens = vttCueTokens(`fixtures/captions/${CORPUS_CLIP}-blocked.vtt`)
    const cueCount = countVttCues(`fixtures/captions/${CORPUS_CLIP}-blocked.vtt`)
    const counters: NetworkCounters = { modelHost: 0, blocked: [] }
    await routeAsrNetwork(page, `http://127.0.0.1:${PORT}`, counters)
    await page.goto('/e2e/captions/fixtures/align-harness.html')
    await page.waitForFunction(() => (globalThis as Record<string, unknown>).__zipscribeCaptionsHarnessReady === true, { timeout: 30_000 })

    const options: AlignRunOptions = {
      fixture: `fixtures/${CORPUS_CLIP}.mp4`,
      refCaption: `fixtures/captions/${CORPUS_CLIP}-blocked.vtt`,
      modelId: 'whisper-tiny-timestamped',
      device: 'wasm',
      language: 'en',
      tier: 'T2',
    }
    const summary = await page.evaluate((runOptions) => (globalThis as unknown as { __zipscribeCaptionsHarness: { runAlign(o: AlignRunOptions): Promise<AlignRunSummary> } }).__zipscribeCaptionsHarness.runAlign(runOptions), options)

    expect(summary.error, `pipeline run failed: ${JSON.stringify(summary.error)} (events: ${JSON.stringify(summary.eventSummary)})`).toBeUndefined()
    expect(summary.cancelled).toBe(false)
    expect(summary.asrWordCount, 'the ASR run produced word tokens').toBeGreaterThan(0)
    expect(summary.captionBlockCount, 'the CART captions parsed into every committed cue').toBe(cueCount)
    expect(summary.captionWordCount, 'the importer tokenized every committed cue word').toBe(captionTokens.length)
    expect(summary.report.wordsTotal).toBe(captionTokens.length)

    // Text-invariance (US-07.3: align never changes texts) — the aligned
    // list must still be the caption stream verbatim (raw texts, sequence
    // exact), otherwise the pairing below is meaningless.
    expect(summary.alignedWords.map((word) => word.text), 'aligned word sequence is the unmodified caption text').toEqual(captionTokens)

    // Non-vacuity: at least SOME words must actually be aligned, or the MAE
    // below would be over an empty set (see header — corpus doctrine).
    expect(summary.report.alignedRatio, `no caption word matched the ASR words (alignedRatio ${summary.report.alignedRatio}) — alignment is vacuous`).toBeGreaterThan(0)

    const gtNorm = groundTruth.map((word) => normalizeToken(word.text))
    const captionNorm = summary.alignedWords.map((word) => normalizeToken(word.text))
    const gtIndices = monotoneGtIndices(captionNorm, gtNorm)
    const errors: number[] = []
    summary.alignedWords.forEach((word, index) => {
      if (word.timing !== 'aligned') return
      const gtIndex = gtIndices[index]!
      if (gtIndex < 0) return
      const gt = groundTruth[gtIndex]!
      errors.push((Math.abs(word.start - gt.start) + Math.abs(word.end - gt.end)) / 2)
    })
    expect(errors.length, 'ASR-aligned, GT-correspondent words feed the MAE').toBeGreaterThan(0)
    const maeMs = (errors.reduce((sum, error) => sum + error, 0) / errors.length) * 1_000
    const limit = baseline * MAE_MULTIPLIER
    expect(maeMs, `word-timing MAE ${maeMs.toFixed(0)} ms exceeds baseline ${baseline} ms (${source}) × ${MAE_MULTIPLIER} = ${limit.toFixed(0)} ms over ${errors.length} aligned words`).toBeLessThanOrEqual(limit)

    expect(counters.blocked, `non-allowlisted origins requested: ${[...new Set(counters.blocked)].join(', ')}`).toEqual([])
    expect(counters.modelHost, 'model weights came from the local cache via the huggingface resolve route').toBeGreaterThan(0)
  })
})
